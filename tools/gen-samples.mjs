// Embeds samples/ into src/lang/basic/samples-data.js
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const base = join(root, 'samples');
const files = {};
const walk = (d) => { for (const f of readdirSync(d).sort()) { const p = join(d, f); if (statSync(p).isDirectory()) walk(p); else files[relative(base, p).split('/').join('\\')] = readFileSync(p, 'utf8'); } };
walk(base);
const out = '// GENERATED by tools/gen-samples.mjs from samples/ - do not edit.\n(function (RC) {\n  RC.SAMPLE_FILES = ' + JSON.stringify(files, null, 1) + ';\n})(RC);\n';
writeFileSync(join(root, 'src/lang/basic/samples-data.js'), out);
console.log('samples-data.js:', Object.keys(files).length, 'files');
