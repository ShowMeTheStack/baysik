// Packs library/<CATEGORY>/*.BAS into src/lang/basic/library-data.js:
//   RC.LIBRARY = { categories: [...], items: [{path, cat, title, level, tags, summary}], blob: '<base64 deflate-raw JSON>' }
// The program texts live in the compressed blob and are decompressed only when the library is opened.
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { deflateRawSync } from 'node:zlib';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const lib = join(root, 'library');
const CAT_NAMES = {
  CONSOLE: 'Console & Text', ALGO: 'Algorithms', DATASTR: 'Data Structures', FILES: 'File I/O', GRAPHICS: 'Graphics',
  MATH: 'Mathematics', GAMES: 'Games', MUSIC: 'Music & Sound', STRINGS: 'Strings & Text Processing', SCIENCE: 'Science & Simulation',
  FRACTALS: 'Fractals & Generative Art', ANIMATE: 'Animation & Sprites', PUZZLES: 'Puzzles & Logic', EDU: 'Education & Quizzes',
  UTIL: 'Utilities & Tools', RECURSE: 'Recursion & Debugging', CLASSIC: 'Classic GW-BASIC', BUSINESS: 'Business & Finance',
  CRYPTO: 'Codes & Cryptography', SYSTEM: 'System, Events & Hardware', ADVENT: 'Adventure, Stories & AI',
};
const items = [], texts = {};
const cats = existsSync(lib) ? readdirSync(lib).filter((d) => statSync(join(lib, d)).isDirectory()).sort() : [];
for (const c of cats) {
  for (const f of readdirSync(join(lib, c)).filter((x) => /\.(BAS|BI)$/i.test(x)).sort()) {
    const text = readFileSync(join(lib, c, f), 'utf8').replace(/\r\n?/g, '\n');
    const field = (k) => { const m = new RegExp("^\\s*(?:\\d+\\s+)?(?:'|REM)\\s*" + k + ':\\s*(.*)$', 'mi').exec(text); return m ? m[1].trim() : ''; };
    const path = c + '\\' + f.toUpperCase();
    texts[path] = text;
    if (/\.BI$/i.test(f)) continue;
    items.push({ path, cat: c, title: field('TITLE') || f, level: (field('LEVEL').split(/\s/)[0] || 'Intermediate'), tags: field('TAGS').split(/\s*,\s*/).filter(Boolean), summary: field('SUMMARY') });
  }
}
const blob = deflateRawSync(Buffer.from(JSON.stringify(texts)), { level: 9 }).toString('base64');
const categories = cats.map((c) => ({ id: c, name: CAT_NAMES[c] || c, count: items.filter((i) => i.cat === c).length }));
writeFileSync(join(root, 'src/lang/basic/library-data.js'), '// GENERATED by tools/gen-library.mjs from library/ - do not edit.\n(function (RC) {\n  RC.LIBRARY = ' +
  JSON.stringify({ categories, items }) + ';\n  RC.LIBRARY.blob = "' + blob + '";\n})(RC);\n');
console.log(`library-data.js: ${items.length} programs in ${cats.length} categories, blob ${(blob.length / 1024).toFixed(0)} KB`);
