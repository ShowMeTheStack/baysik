// Converts raw VGA BIOS font dumps (256 glyphs, 1 byte per scanline) into src/core/fonts.js
// Fonts: IBM VGA ROM 8x8, EGA ROM 8x14, VGA ROM 8x16 (raw dumps from the
// viler-int10h/vga-text-mode-fonts collection).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const fonts = { 8: 'BIOS.F08', 14: 'EGA8.F14', 16: 'VGA8.F16' };
let out = '// GENERATED by tools/fonts2js.mjs - do not edit.\n' +
  '// IBM PC ROM bitmap fonts (8x8 VGA BIOS, 8x14 EGA, 8x16 VGA), 256 CP437 glyphs each.\n' +
  '(function (RC) {\n  const b64 = {\n';
for (const [h, f] of Object.entries(fonts)) {
  const data = readFileSync(join(root, 'assets/fonts', f));
  if (data.length !== 256 * Number(h)) throw new Error(`${f}: unexpected size ${data.length}`);
  out += `    ${h}: '${data.toString('base64')}',\n`;
}
out += `  };
  RC.fonts = {};
  for (const h in b64) {
    const s = atob(b64[h]);
    const a = new Uint8Array(s.length);
    for (let i = 0; i < s.length; i++) a[i] = s.charCodeAt(i);
    RC.fonts[h] = a;
  }
})(RC);
`;
writeFileSync(join(root, 'src/core/fonts.js'), out);
console.log('wrote src/core/fonts.js');
